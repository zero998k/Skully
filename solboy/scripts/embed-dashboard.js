// Bakes src/dashboard.html (and the version from package.json) into JS modules so they ship inside the single-file app.
import fs from 'node:fs';

const html = fs.readFileSync(new URL('../src/dashboard.html', import.meta.url), 'utf8');
fs.writeFileSync(
  new URL('../src/dashboard-html.js', import.meta.url),
  `// Generated by scripts/embed-dashboard.js from src/dashboard.html. Edit that file, not this one.\nexport default ${JSON.stringify(html)};\n`,
);

const { version } = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
fs.writeFileSync(
  new URL('../src/version.js', import.meta.url),
  `// Generated by scripts/embed-dashboard.js from package.json. Change the version there.\nexport const VERSION = ${JSON.stringify(version)};\n`,
);

// The Pulse terminal page, with the TradingView chart library baked in so it works without a CDN.
const chartLib = fs.readFileSync(new URL('../node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js', import.meta.url), 'utf8');
const pulse = fs.readFileSync(new URL('../src/pulse.html', import.meta.url), 'utf8').replace('/*__CHART_LIB__*/', () => chartLib.replace(/<\/script/gi, '<\\/script'));
fs.writeFileSync(
  new URL('../src/pulse-html.js', import.meta.url),
  `// Generated by scripts/embed-dashboard.js from src/pulse.html. Edit that file, not this one.\nexport default ${JSON.stringify(pulse)};\n`,
);
