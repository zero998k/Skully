// Bakes src/dashboard.html (and the version from package.json) into JS modules so they ship inside the single-file app.
import fs from 'node:fs';

// Brand assets baked into both pages: the logo font (Syne, OFL) and the mascot (rendered in Blender).
const asset = (name) => fs.readFileSync(new URL(`../src/assets/${name}`, import.meta.url)).toString('base64');
const brand = (page) => page.replaceAll('__LOGO_FONT__', asset('syne-800.woff2')).replaceAll('__MASCOT__', `data:image/png;base64,${asset('mascot.png')}`);
const html = brand(fs.readFileSync(new URL('../src/dashboard.html', import.meta.url), 'utf8'));
// The friend's Finder page (share link) reuses the dashboard's styles, Finder markup and Finder code.
const between = (text, from, to) => {
  const i = text.indexOf(from), j = text.indexOf(to, i + from.length);
  if (i < 0 || j < 0) throw new Error(`embed: can't find ${from}`);
  return text.slice(i, j);
};
const section = `${between(html, '<section class="panel tabpage" id="tab-finder">', '</section>')}</section>`.replace('class="panel tabpage"', 'class="panel"');
const guest = brand(fs.readFileSync(new URL('../src/guest.html', import.meta.url), 'utf8'))
  .replace('/*DASHBOARD_STYLE*/', () => between(html, '<style>', '</style>').slice('<style>'.length))
  .replace('<!--FINDER_SECTION-->', () => section)
  .replace('/*FINDER_JS*/', () => between(html, '// (everything from here to the keyboard section is also', '/* ---------- keyboard ---------- */'));
fs.writeFileSync(
  new URL('../src/dashboard-html.js', import.meta.url),
  `// Generated by scripts/embed-dashboard.js from src/dashboard.html and src/guest.html. Edit those, not this.\nexport default ${JSON.stringify(html)};\nexport const GUEST_HTML = ${JSON.stringify(guest)};\n`,
);

const { version } = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
fs.writeFileSync(
  new URL('../src/version.js', import.meta.url),
  `// Generated by scripts/embed-dashboard.js from package.json. Change the version there.\nexport const VERSION = ${JSON.stringify(version)};\n`,
);
